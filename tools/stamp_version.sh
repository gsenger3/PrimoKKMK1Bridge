#  Stamps the version for a build: Major.minor from the VERSION file, and a new Build ID from the date and time
#  of the build (YYYYMMDD.HHMM). Writes build/Version.swift, which the bridge compiles in, and build/version.env
#  (APP_VERSION, APP_BUILD_ID), which the build scripts read. Prints the version string, e.g. 1.0 (20261109.2315).
#  Run by bridge/build.sh and editor/build.sh; build/ isn't in git, so building never changes a tracked file.

set -euo pipefail
cd "${0:A:h}/.."

version=$(tr -d '[:space:]' < VERSION)
if [[ ! $version =~ '^[0-9]+\.[0-9]+$' ]]; then
    echo "VERSION must be Major.minor, like 1.0; it says \"$version\"" >&2
    exit 1
fi
build_id=$(date +%Y%m%d.%H%M)

mkdir -p build
cat > build/Version.swift <<EOF
// Generated by tools/stamp_version.sh for this build; don't edit. Major.minor comes from the VERSION file.
let appVersion = "$version"
let appBuildID = "$build_id"
let appVersionString = "$version ($build_id)"
EOF
printf 'APP_VERSION=%s\nAPP_BUILD_ID=%s\n' "$version" "$build_id" > build/version.env
echo "$version ($build_id)"
